test('doc-08 inline edit of matrix in the document updates editor and card indicator', async ({ page }) => {
  await openApp(page)
  await loadExample(page)
  await toMode(page, 'Document')
  const m = docSection(page, 'baseline').getByTestId('doc-matrix')
  await m.getByRole('textbox', { name: 'Cell 2,1' }).fill('Changed')
  await m.getByRole('textbox', { name: 'Option 2 name' }).fill('LogReg')
  await m.getByRole('button', { name: 'Choose option 2' }).click()
  await expect(m.locator('tbody tr').nth(1)).toHaveAttribute('data-chosen', 'true')
  await m.getByRole('textbox', { name: 'Cell 1,1' }).fill('')
  await toMode(page, 'Canvas')
  await expect(indicator(card(page, 'baseline'), 'Trade-offs')).toHaveAttribute('data-state', 'off')
  await openDetails(page, 'baseline')
  const d = dialog(page)
  await expect(d.getByRole('textbox', { name: 'Cell 2,1' })).toHaveValue('Changed')
  await expect(d.getByRole('textbox', { name: 'Option 2 name' })).toHaveValue('LogReg')
  await expect(d.getByRole('button', { name: 'Choose option 2' })).toHaveAttribute('aria-pressed', 'true')
})

test('sync-01 canvas edits show in document and back, for key properties, rationale, trade-offs and diagram', async ({ page }) => {
  await openApp(page)
  // Canvas -> Document
  await setCardValue(page, 'monitoring', 'Data Drift', 'PSI < 0.2')
  await openDetails(page, 'monitoring')
  const d = dialog(page)
  await d.getByRole('textbox', { name: 'Rationale' }).fill('Watch drift daily')
  await addCriterion(d, 'Cost')
  await addOption(d, 'Batch', ['Low'])
  await addOption(d, 'Stream', ['High'])
  await d.getByRole('button', { name: 'Choose option 1' }).click()
  await drawRectangle(page)
  await closeEditor(page)
  await toMode(page, 'Document')
  const s = docSection(page, 'monitoring')
  await expect(s.getByTestId('key-properties')).toContainText('PSI < 0.2')
  await expect(s.getByTestId('rationale')).toContainText('Watch drift daily')
  await expect(s.getByRole('textbox', { name: 'Option 2 name' })).toHaveValue('Stream')
  await expect(s.getByRole('img', { name: 'Monitoring diagram' })).toBeVisible()
  // Document -> Canvas
  await s.getByRole('button', { name: 'Edit Data Drift' }).click()
  await s.getByRole('textbox', { name: 'Data Drift' }).fill('KS test')
  await s.getByRole('textbox', { name: 'Data Drift' }).press('Enter')
  await s.getByRole('textbox', { name: 'Monitoring rationale' }).click()
  await page.keyboard.press('ControlOrMeta+End')
  await page.keyboard.type(' and weekly')
  await s.getByRole('textbox', { name: 'Cell 2,1' }).fill('Very high')
  await toMode(page, 'Canvas')
  await expect(card(page, 'monitoring').getByRole('button', { name: 'Edit Data Drift' })).toHaveText('KS test')
  await expect(indicator(card(page, 'monitoring'), 'Diagram')).toHaveAttribute('data-state', 'on')
  await expect(card(page, 'monitoring').getByTestId('thumbnail').locator('img')).toBeVisible()
  await openDetails(page, 'monitoring')
  await expect(d.getByRole('textbox', { name: 'Rationale' })).toContainText('Watch drift daily and weekly')
  await expect(d.getByRole('textbox', { name: 'Cell 2,1' })).toHaveValue('Very high')
})
